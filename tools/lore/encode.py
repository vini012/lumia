#!/usr/bin/env python3
"""Lumiar text-data encoder (dev tool, not shipped).

Reads the plaintext narrative JSON that is kept OUTSIDE the repository and writes `js/lore.js`, which holds the
same data as `L.LORE` = base64( UTF-8 JSON  XOR  repeating key ) plus the lazy decoders `L.T`, `L.TL` and `L.TX`.
This file must never contain any of the narrative text itself.

usage:
  python3 tools/lore/encode.py [SRC_JSON] [OUT_JS]      (defaults: $LUMIAR_LORE_SRC or the v5 docs copy, js/lore.js)
  python3 tools/lore/encode.py --word TEXT             print TEXT encoded for L.TX('...') (short identifiers)
  python3 tools/lore/encode.py --check [SRC_JSON]      decode js/lore.js again and compare with the source

Keys whose name starts with '_' (comments) are dropped. The output is deterministic (same input -> same file).
"""
import base64
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
DEFAULT_SRC = os.environ.get('LUMIAR_LORE_SRC', '/home/claude/v5docs/story_src.json')
DEFAULT_OUT = os.path.join(ROOT, 'js', 'lore.js')
KEY = bytes.fromhex('d678d35c5cec790a15eb6c17f3776646f0eef9013d4d58bbd72c09528e')


def xor(data: bytes) -> bytes:
    return bytes(b ^ KEY[i % len(KEY)] for i, b in enumerate(data))


def enc(text: str) -> str:
    return base64.b64encode(xor(text.encode('utf-8'))).decode('ascii')


def dec(b64: str) -> str:
    return xor(base64.b64decode(b64)).decode('utf-8')


def strip(o):
    if isinstance(o, dict):
        return {k: strip(v) for k, v in o.items() if not k.startswith('_')}
    if isinstance(o, list):
        return [strip(v) for v in o]
    return o


def payload(src_path):
    with open(src_path, encoding='utf-8') as f:
        data = strip(json.load(f))
    return data, json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=False)


JS = r"""/* Lumiar: encoded text data + decoder. GENERATED by tools/lore/encode.py, do not edit by hand. */
'use strict';
window.L = window.L || {};
(function (L) {
  L.LORE = '__B64__';
  const K = [__KEY__];
  let data = null; const cache = new Map();
  function unmask(b64) {
    const s = atob(b64), u = new Uint8Array(s.length);
    for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i) ^ K[i % K.length];
    if (typeof TextDecoder !== 'undefined') return new TextDecoder('utf-8').decode(u);
    let r = ''; for (let i = 0; i < u.length; i += 4096) r += String.fromCharCode.apply(null, u.subarray(i, i + 4096));
    return decodeURIComponent(escape(r));
  }
  function root() { if (!data) { try { data = JSON.parse(unmask(L.LORE)); } catch (e) { console.warn('lore', e); data = {}; } } return data; }
  // dotted path; inside arrays a segment is an index ('lines.2') or the id of an element ('notes.n01.text')
  function walk(path) {
    if (cache.has(path)) return cache.get(path);
    let o = root();
    if (path) for (const seg of String(path).split('.')) {
      if (o == null) break;
      if (Array.isArray(o)) o = /^\d+$/.test(seg) ? o[+seg] : o.find(e => e && e.id === seg);
      else o = Object.prototype.hasOwnProperty.call(o, seg) ? o[seg] : undefined;
    }
    cache.set(path, o); return o;
  }
  // string (or number) at path, else fallback ('' by default)
  L.T = function (path, fallback) { const v = walk(path); return typeof v === 'string' ? v : typeof v === 'number' ? String(v) : (fallback === undefined ? '' : fallback); };
  // any value at path (object, array, string...), undefined when missing
  L.TL = function (path) { return walk(path || ''); };
  // short identifiers that must not appear in plain text in the sources
  L.TX = function (b64) { try { return unmask(b64); } catch (e) { return ''; } };
})(window.L);
"""


def write(src, out):
    data, text = payload(src)
    b64 = enc(text)
    js = JS.replace('__B64__', b64).replace('__KEY__', ','.join(str(b) for b in KEY))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    n_notes = len(data.get('notes', []))
    print(f'wrote {os.path.relpath(out, ROOT)}: {len(js)} bytes, {n_notes} notes, '
          f'{len(data.get("dreams", []))} dreams, {len(data.get("thoughts", []))} thoughts, '
          f'{len(data.get("tasks", []))} tasks, {len(data.get("spells", []))} spells')
    check(src, out)


def check(src, out):
    data, _ = payload(src)
    with open(out, encoding='utf-8') as f:
        js = f.read()
    b64 = js.split("L.LORE = '", 1)[1].split("'", 1)[0]
    back = json.loads(dec(b64))
    if back != data:
        sys.exit('ERROR: round trip mismatch')
    print('round trip ok')


if __name__ == '__main__':
    a = sys.argv[1:]
    if a and a[0] == '--word':
        print(enc(' '.join(a[1:])))
    elif a and a[0] == '--check':
        check(a[1] if len(a) > 1 else DEFAULT_SRC, DEFAULT_OUT)
    else:
        write(a[0] if a else DEFAULT_SRC, a[1] if len(a) > 1 else DEFAULT_OUT)
